"""导出训练好的学生模型 → MCU C 文件 (model_factory 格式, 归一化折叠进权重).

默认读取 runs/kamm533_student.pt (pipeline.py 的产物), 架构从 checkpoint 的
arch 字段自动识别. 生成 nn_model_<arch>_v4.c/.h:

  - polar_encode 输出原始物理量 (v, delta, d, theta), 归一化折叠进第一层权重:
      state_enc.weight[:,0] /= V_MAX(5.0)    [:,1] /= DELTA_MAX
      target_enc.weight[:,0] /= D_SCALE(5.0) [:,1] /= PI
  - 输出钳位走 g_model_active->nn_a_max / nn_a_brake_max / nn_o_max (运行时)
  - 末尾打印 model_desc_t 符号名, 供 model_factory / config.h 注册

用法:
  python export_mcu.py                                  # 默认 runs/kamm533_student.pt
  python export_mcu.py --ckpt runs/xxx.pt --out-dir .   # 指定输入/输出目录
"""
